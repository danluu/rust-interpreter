#!/usr/bin/env python3
"""Qualify the completed test-only build and run larger deterministic seed ranges."""
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'scripts'))
from build_runtime_candidate import test_counts
from compare_saved_runtime import acquire_lock, sha
from workflow_io import capture, require_space, write_json as write


def main():
    run = 'generated-cfg-campaign-01'
    with (ROOT / '.work/benchmark.lock').open('a') as lock:
        acquire_lock(lock, 45)
        require_space(ROOT, 3.5)
        work = ROOT / '.work' / run
        work.mkdir(exist_ok=False)
        build = ROOT / '.work/generated-cfg-build-01'
        plan = json.loads((build / 'plan.json').read_text())
        status_path = ROOT / '.work/experiments/generated-cfg-build-01/status.json'
        status = json.loads(status_path.read_text())
        assert status['status'] == 'finished' and status['returncode'] == 1
        assert status['owner'] == status['cwd'] == str(ROOT)
        assert sha(status_path.with_name('plan.json')) == status['plan_sha256']
        assert sha(status_path.with_name('command.log')) == status['log_sha256']
        log = status_path.with_name('command.log').read_text()
        assert 'insufficient free disk:' in log and 'no child started' in log
        commands = json.loads((build / 'commands.json').read_text())
        assert [c['label'] for c in commands] == ['test-debug', 'test-release']
        assert all(c['returncode'] == 0 for c in commands)
        assert all(sha(ROOT / p) == digest for p, digest in plan['frozen'].items())
        paths = [Path(__file__), build / 'plan.json', build / 'commands.json', status_path,
                 status_path.with_name('plan.json'), status_path.with_name('command.log')]
        paths += [ROOT / name for name in ['scripts/build_runtime_candidate.py', 'scripts/compare_saved_runtime.py', 'scripts/workflow_io.py']]
        binaries, counts = {}, {}
        for profile in ['debug', 'release']:
            stdout, stderr = [build / ('test-' + profile + '.' + suffix) for suffix in ['stdout', 'stderr']]
            counts[profile] = test_counts(stdout.read_text() + stderr.read_text())
            assert counts[profile] == dict(passed=362, ignored=1)
            matches = re.findall(r'Running tests/generated_cfg\.rs \(([^\n]+)\)', stderr.read_text())
            assert len(matches) == 1
            binary = (ROOT / matches[0]).resolve(strict=True)
            expected_parent = Path(plan['target']) / profile / 'build/rust-interp-bytecode'
            assert binary.is_relative_to(expected_parent) and binary.name.startswith('generated_cfg-')
            assert binary.stat().st_mtime <= status['finished_at']
            binaries[profile] = binary
            paths += [stdout, stderr, binary]
        paths += [ROOT / path for path in plan['frozen']]
        frozen = {str(p.relative_to(ROOT)): sha(p) for p in paths}
        ranges = [dict(start=32, cases=256), dict(start=1 << 63, cases=256), dict(start=(1 << 64)-256, cases=256)]
        write(work / 'plan.json', dict(owner=str(ROOT), source_commit=plan['source_commit'], frozen=frozen,
            ranges=ranges, binaries={k: str(v) for k, v in binaries.items()}, host_tests=counts,
            vm_build='not started: storage guard after both successful test profiles',
            scope='Additional generated bytecode correctness checks; no Rust frontend or performance claim.'))
        records = []
        for profile, binary in binaries.items():
            for index, selection in enumerate(ranges):
                require_space(ROOT, 3)
                env = {k: v for k, v in os.environ.items() if not k.startswith(('RUST_INTERP_', 'RUSTDEV_'))}
                env.update(RUST_INTERP_DIFF_SEED=str(selection['start']), RUST_INTERP_DIFF_CASES=str(selection['cases']),
                    RUST_INTERP_DIFF_OUTPUT=str(work / 'failures'))
                command = [str(binary), '--exact', 'native::generated_cfgs_match_interpreter_across_native_modes_and_budgets', '--nocapture']
                child, stdout, stderr = capture(command, cwd=ROOT, env=env, receipt_path=work / 'active.json',
                    receipt=dict(profile=profile, index=index, selection=selection))
                row = dict(profile=profile, index=index, selection=selection, command=command, pid=child.pid,
                    returncode=child.returncode, stdout=stdout, stderr=stderr)
                records.append(row)
                write(work / 'records.json', records)
                assert child.returncode == 0 and test_counts(stdout + stderr) == dict(passed=1, ignored=0), stderr + stdout
                print(profile, selection, 'passed', flush=True)
        assert all(sha(ROOT / p) == digest for p, digest in frozen.items())
        out = ROOT / 'results' / run
        out.mkdir(exist_ok=False)
        write(out / 'summary.json', dict(status='passed', source_commit=plan['source_commit'], host_tests=counts,
            commands=len(records), additional_distinct_seeds=768, profiles=['debug', 'release'],
            additional_seed_profile_cases=1536, source_and_binaries_unchanged=True,
            vm_build_completed=False, runtime_source_changed=False, performance_measurement=False,
            raw=str(work.relative_to(ROOT)), plan_sha256=sha(work / 'plan.json'), records_sha256=sha(work / 'records.json')))


if __name__ == '__main__':
    main()
